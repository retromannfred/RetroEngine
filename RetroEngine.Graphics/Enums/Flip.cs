namespace RetroEngine.Graphics
{
    /// <summary>
    /// Enumerates all flipping moves of an image.
    /// </summary>
    public enum Flip
    {
        /// <summary>
        /// Defines no flip.
        /// </summary>
        None = 0,

        /// <summary>
        /// Defines an horizontal flip.
        /// </summary>
        X = 1,

        /// <summary>
        /// Defines a vertical flip.
        /// </summary>
        Y = 2,

        /// <summary>
        /// Defines an horizontal and vertical flip.
        /// </summary>
        Both = 3
    }
}
