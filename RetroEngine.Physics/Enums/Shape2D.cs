namespace RetroEngine.Physics
{
    /// <summary>
    /// Enumerates shapes of a collider.
    /// </summary>
    public enum Shape2D
    {
        /// <summary>
        /// Rectangle with a width and a height.
        /// </summary>
        Rectangle,

        /// <summary>
        /// Circle with a radius.
        /// </summary>
        Circle,

        /// <summary>
        /// Convex polygon with undefined vertices.
        /// </summary>
        Polygon
    }
}
